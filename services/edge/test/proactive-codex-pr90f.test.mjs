// Codex PR90 round 6 (d544ea2): late sync keeps the device's until; push generation + claim token (an old completion
// never swallows a re-armed push); 'sending' lease recovery (unsent → resend, unknown → resend under the same collapse id);
// offline suggestions created server-side from the device (idempotent by client id).
import test from 'node:test'; import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createProactiveService } from '../supabase/functions/_shared/proactive/service.mjs';
import { createMemoryStore } from '../supabase/functions/_shared/proactive/memory-store.mjs';
import { createDecisionService } from '../supabase/functions/_shared/proactive/decision.mjs';

const U = crypto.randomUUID(), BASE = '/catpaw/proactive/v1';
const TOK = { device_id: 'd1', kind: 'apns', token: 'ab'.repeat(32), environment: 'sandbox', bundle_id: 'app.catpaw' };
const fakeLLM = out => ({ lastRoute: () => 'fake', decide: async () => out });
function setup({ t = '2026-10-15T02:00:00Z', apns } = {}) {
  const clock = { t: Date.parse(t) }, store = createMemoryStore(), sent = [];
  apns ??= { configured: true, send: async (tk, ev) => { sent.push(ev); return { ok: true }; } };
  const decision = createDecisionService({ store, model: fakeLLM({ decision: 'notify', reason: '该出发了', confidence: 0.9, suggested_actions: ['create_reminder', 'snooze', 'dismiss'] }), now: () => clock.t });
  const svc = createProactiveService({ store, decision, apns, schedulerSecret: 's', now: () => clock.t, verifyUser: async () => ({ sub: U }) });
  const call = async (method, path, body) => { const r = await svc.handle(new Request('https://x/functions/v1/catpaw-proactive' + path, { method, headers: { authorization: 'Bearer u' }, body: body ? JSON.stringify(body) : undefined })); return { status: r.status, body: await r.json() }; };
  return { clock, store, svc, call, sent };
}
const meeting = (ctx = {}) => ({ context: { time_zone: 'Asia/Shanghai', ...ctx }, signals: [{ type: 'meeting_upcoming', source: 'calendar', dedupe_key: 'evt-f-' + crypto.randomUUID(), data: { title: '评审', minutes_until: 20 } }] });

test('PR90f #3: a late sync keeps the original until (already past → recorded as expired, resurfaces)', async () => {
  const { call, store, clock } = setup({ t: '2026-10-15T02:20:00Z' });
  const id = (await call('POST', BASE + '/evaluate', meeting())).body.event_id;
  const until = '2026-10-15T02:10:00.000Z';   // chosen on the device at 02:00, synced at 02:20
  await call('POST', `${BASE}/suggestions/${id}/action`, { action: 'snooze', operation_id: `op-${id}-snooze`, until });
  const st = (await store.getEvent(U, id)).payload.suggestion;
  assert.equal(st.taken.at(-1).until, until, 'the device until is kept'); assert.equal(st.taken.at(-1).expired, true);
  assert.equal(st.snooze_until, until);
  await store.resurfaceSnoozed(new Date(clock.t).toISOString());
  assert.equal((await store.getEvent(U, id)).payload.suggestion.status, 'pending', 'expired snooze resurfaces at once');
});

test('PR90f #3: golden device payloads (generated by the Swift client runner) replay to the same state on the server', async () => {
  const g = JSON.parse(readFileSync(new URL('./fixtures/proactive-sync-golden.json', import.meta.url)));
  const { call, store, clock } = setup({ t: g.server_now });
  const id = (await call('POST', BASE + '/evaluate', meeting())).body.event_id;
  for (const r of g.requests) {
    const body = JSON.parse(JSON.stringify(r.body).replaceAll(g.local_id, id));
    const res = await call('POST', `${BASE}/suggestions/${id}/${r.route}`, body); assert.equal(res.status, 200, JSON.stringify(res.body));
  }
  const st = (await store.getEvent(U, id)).payload.suggestion;
  assert.equal(st.status, g.expect.status); assert.deepEqual(st.taken.map(t => t.action), g.expect.taken);
  assert.equal(Date.parse(st.snooze_until), Date.parse(g.expect.snooze_until), 'cloud restores the same until instant as the device');
  assert.deepEqual(st.taken.map(t => Date.parse(t.until)), [Date.parse(g.requests[0].body.until)], 'the kept snooze is the device\'s first one, its own until');
  void clock;
});

test('PR90f #4: an old send completing after the row was re-armed does not swallow the new round', async () => {
  let release, held = true; const sent = [];
  const apns = { configured: true, send: async (tk, ev) => { if (held) { held = false; await new Promise(r => { release = r; }); } sent.push(ev.id); return { ok: true }; } };
  const { call, svc, store, clock } = setup({ apns }); await store.upsertToken(U, TOK);
  const id = (await call('POST', BASE + '/evaluate', meeting({ delivery: 'remote' }))).body.event_id;
  const first = svc.flushPush();                                   // holds 'sending'
  await new Promise(r => setTimeout(r, 10));
  await call('POST', `${BASE}/suggestions/${id}/action`, { action: 'snooze', operation_id: 'op-s', minutes: 10 });
  clock.t += 11 * 60_000; await store.resurfaceSnoozed(new Date(clock.t).toISOString());   // re-armed: new generation
  release(); await first;                                          // old completion arrives late
  assert.equal((await store.getEvent(U, id)).push_state, 'pending', 'old claim cannot complete the new round');
  await svc.flushPush();
  assert.equal(sent.length, 2, 'the re-armed round is sent');
});

test('PR90f #4: a crashed claim is recovered after the lease (never attempted → resent; unknown → resent, same collapse id)', async () => {
  const { call, svc, store, clock, sent } = setup(); await store.upsertToken(U, TOK);
  const a = (await call('POST', BASE + '/evaluate', meeting({ delivery: 'remote' }))).body.event_id;
  const b = (await call('POST', BASE + '/evaluate', meeting({ delivery: 'remote' }))).body.event_id;
  const T = () => new Date(clock.t).toISOString();
  const ca = await store.claimPush(a, T()); assert.ok(ca?.claim, 'claim token');      // crashed before sending
  const cb = await store.claimPush(b, T()); await store.markPushAttempt(b, cb.claim, T());  // crashed after APNs was called
  await svc.flushPush(); assert.equal(sent.length, 0, 'within the lease nothing is touched');
  clock.t += 5 * 60_000; await svc.flushPush();
  assert.equal(sent.length, 1, 'recovered rows go out (two of one user coalesce into one push, as before)');
  const eb = await store.getEvent(U, b); assert.ok(['sent', 'skipped'].includes(eb.push_state)); assert.equal(eb.push_recovered, 'unknown');
  assert.notEqual((await store.getEvent(U, a)).push_state, 'sending');
  assert.equal((await store.getEvent(U, a)).push_recovered, 'unsent');
  assert.equal(await store.finishPush(a, ca.claim, 'failed', 'late'), false, 'the crashed claim can never complete');
});

test('PR90f #5: an offline device suggestion is created server-side once (idempotent by client id), then its ops replay', async () => {
  const { call, store } = setup();
  const body = { client_id: 'local-abc', title: '评审', reason: '该出发了', actions: ['create_reminder', 'snooze', 'dismiss'], decision: 'notify', created_at: '2026-10-15T01:50:00Z' };
  const r1 = await call('POST', BASE + '/suggestions', body), r2 = await call('POST', BASE + '/suggestions', body);
  assert.equal(r1.status, 200, JSON.stringify(r1.body)); assert.equal(r1.body.suggestion.id, r2.body.suggestion.id, 'same record');
  const id = r1.body.suggestion.id, ev = await store.getEvent(U, id);
  assert.equal(ev.payload.delivery, 'device'); assert.equal(ev.push_state, 'skipped', 'never pushed by the server');
  await call('POST', `${BASE}/suggestions/${id}/action`, { action: 'dismiss', operation_id: 'op-local-abc-dismiss' });
  assert.equal((await store.getEvent(U, id)).payload.suggestion.status, 'dismissed');
});

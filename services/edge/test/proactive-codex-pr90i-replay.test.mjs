// p90i P3: one continuous recording of the REAL Edge handler (createProactiveService + createDecisionService) for a
// cloud card's life on the device: GET card → snooze → dismiss (first attempt refused 403 feature_disabled, retried)
// → undo (restores the snooze) → undo again, with a GET of the card after every write. The device's iOS host test
// ProactiveEngineHostTests/testCloudCardContinuousReplay replays this file: every request the client encodes must be
// byte-identical to `request` here (the client's own sortedKeys encoding), and it decodes exactly `response`.
// Placeholders: SERVER-ID = the event id; __UNTIL__ = the device's snooze until (ISO 8601, no fraction).
// Regenerate: CATPAW_WRITE_GOLDEN=1 node --test test/proactive-codex-pr90i-replay.test.mjs
import test from 'node:test'; import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createProactiveService } from '../supabase/functions/_shared/proactive/service.mjs';
import { createMemoryStore } from '../supabase/functions/_shared/proactive/memory-store.mjs';
import { createDecisionService } from '../supabase/functions/_shared/proactive/decision.mjs';

const U = '00000000-0000-4000-8000-0000000000aa', BASE = '/catpaw/proactive/v1';
const fakeLLM = { lastRoute: () => 'fake', decide: async () => ({ decision: 'notify', reason: '该出发了', confidence: 0.9, suggested_actions: ['snooze', 'dismiss'] }) };
// What the device's JSONSerialization(.sortedKeys) writes for these flat string bodies.
const encode = o => JSON.stringify(Object.fromEntries(Object.keys(o).sort().map(k => [k, o[k]])));

export async function record() {
  const clock = { t: Date.parse('2026-10-15T02:00:00Z') }, store = createMemoryStore(); let allowed = true;
  const decision = createDecisionService({ store, model: fakeLLM, now: () => clock.t });
  const svc = createProactiveService({ store, decision, schedulerSecret: 's', now: () => clock.t, verifyUser: async () => ({ sub: U }), allow: async () => allowed });
  const call = async (method, path, raw) => {
    const r = await svc.handle(new Request('https://x/functions/v1/catpaw-proactive' + BASE + '/' + path, { method, headers: { authorization: 'Bearer u', 'content-type': 'application/json' }, body: raw ?? undefined }));
    return { status: r.status, body: await r.json() };
  };
  const ev = await call('POST', 'evaluate', JSON.stringify({ context: { time_zone: 'Asia/Shanghai', delivery: 'remote' }, signals: [{ type: 'meeting_upcoming', source: 'calendar', dedupe_key: 'replay-1', data: { title: '评审会', location: '', minutes_until: 40 } }] }));
  const id = ev.body.event_id, until = new Date(clock.t + 10 * 60_000).toISOString().replace('.000Z', 'Z');
  const ex = [];
  const get = async () => { const r = await call('GET', `suggestions/${id}`); ex.push({ method: 'GET', path: `suggestions/${id}`, request: null, status: r.status, response: r.body }); return r; };
  const post = async (path, body) => { const raw = encode(body); const r = await call('POST', path, raw); ex.push({ method: 'POST', path, request: raw, status: r.status, response: r.body }); return r; };
  await get();
  await post(`suggestions/${id}/action`, { action: 'snooze', operation_id: `op-${id}-snooze`, until }); await get();
  allowed = false; await post(`suggestions/${id}/action`, { action: 'dismiss', operation_id: `op-${id}-dismiss` }); allowed = true;   // refused
  await post(`suggestions/${id}/action`, { action: 'dismiss', operation_id: `op-${id}-dismiss` }); await get();                     // retried
  await post(`suggestions/${id}/undo`, { operation_id: `undo-${id}-g0` }); await get();
  await post(`suggestions/${id}/undo`, { operation_id: `undo-${id}-g1` }); await get();
  const text = JSON.stringify({ comment: 'p90i P3 — generated by test/proactive-codex-pr90i-replay.test.mjs from the real Edge handler; do not edit by hand.', exchanges: ex }, null, 2)
    .replaceAll(id, 'SERVER-ID').replaceAll(until, '__UNTIL__')
    .replace(/"createdAt": "[^"]+"/g, '"createdAt": "2026-10-15T02:00:00.000Z"');   // the card's insert time is wall clock
  return JSON.parse(text);
}

test('p90i P3: the continuous replay fixture is exactly what the real Edge handler answers (incl. the 403 refusal)', async () => {
  const got = await record(), url = new URL('./fixtures/proactive-cloud-card-replay.json', import.meta.url);
  if (process.env.CATPAW_WRITE_GOLDEN === '1') writeFileSync(url, JSON.stringify(got, null, 2) + '\n');
  assert.ok(existsSync(url), 'replay fixture committed'); assert.deepEqual(got, JSON.parse(readFileSync(url)));
  const st = got.exchanges.map(e => e.method === 'GET' ? e.response.suggestion.status : e.status);
  assert.deepEqual(st, ['pending', 200, 'snoozed', 403, 200, 'dismissed', 200, 'snoozed', 200, 'pending']);
  assert.equal(got.exchanges[3].response.error ?? got.exchanges[3].response.code, 'feature_disabled');
  const restored = got.exchanges[7].response.suggestion.taken.at(-1);
  assert.ok(String(restored.until).startsWith('2026-10-15T02:10:00'), 'restored snooze keeps the device until (' + restored.until + ')');
});
